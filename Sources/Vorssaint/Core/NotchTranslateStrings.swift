import Foundation

struct NotchTranslateStrings {
    let title: String
    let description: String
    let placeholder: String
    let detectedFormat: String
    let autoDetect: String
    let translateInto: String
    let swap: String
    let copy: String
    let copied: String
    let translate: String
    let translateHint: String
    let history: String
    let historyEmpty: String
    let clearHistory: String
    let failureApple: String
    let failurePair: String
    let failureKey: String
    let failureServerURL: String
    let failureUnauthorized: String
    let failureQuota: String
    let failureRate: String
    let failureOffline: String
    let failureServerFormat: String
    let failureResponse: String
    let failureTooLong: String
    let failureGeneric: String
    let engine: String
    let engineMac: String
    let engineOnline: String
    let engineMacHint: String
    let engineOnlineHint: String
    let provider: String
    let serverURL: String
    let model: String
    let apiKey: String
    let optional: String
    let test: String
    let testWorks: String
    let manageLanguages: String
    let keepHistory: String
    let keepFor: String
    let forever: String
    let day: String
    let week: String
    let month: String
    let translateFrom: String
    let listen: String
    let clear: String
    let dictionary: String
    let openInWindow: String
    let close: String

    func detected(_ language: String) -> String { String(format: detectedFormat, language) }

    func failure(_ failure: NotchTranslateFailure) -> String {
        switch failure {
        case .unsupportedPair: return failurePair
        case .missingKey: return failureKey
        case .invalidServer: return failureServerURL
        case .unauthorized: return failureUnauthorized
        case .quotaExceeded: return failureQuota
        case .rateLimited: return failureRate
        case .offline: return failureOffline
        case .server(let status): return String(format: failureServerFormat, status)
        case .badResponse: return failureResponse
        case .tooLong: return failureTooLong
        case .unknown: return failureGeneric
        }
    }

    func retention(_ retention: ScratchpadRetention) -> String {
        switch retention {
        case .never: return forever
        case .day: return day
        case .week: return week
        case .month: return month
        }
    }
}

