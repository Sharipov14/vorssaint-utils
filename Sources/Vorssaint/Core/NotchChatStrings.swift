struct NotchChatStrings {
    let title: String
    let settingsDescription: String
    let noProviders: String
    let addProvider: String
    let customProvider: String
    let name: String
    let wire: String
    let wireOpenAI: String
    let wireAnthropic: String
    let baseURL: String
    let invalidURL: String
    let apiKey: String
    let optional: String
    let models: String
    let addModel: String
    let removeModel: String
    let fetchModels: String
    let fetchedFormat: String
    let noModelsFound: String
    let test: String
    let testWorks: String
    let needsModel: String
    let modelCountFormat: String
    let keyMissing: String
    let enabled: String
    let deleteProvider: String
    let deleteTitleFormat: String
    let deleteMessage: String
    let delete: String
    let cancel: String
    let failureKey: String
    let failureServerURL: String
    let failureUnauthorized: String
    let failureNotFound: String
    let failureRate: String
    let failureOffline: String
    let failureServerFormat: String
    let failureResponse: String
    let placeholder: String
    let emptyFormat: String
    let send: String
    let stop: String
    let newChat: String
    let retry: String
    let openSettings: String
    let needsSetup: String
    let model: String
    let thinking: String

    func wire(_ wire: ChatWire) -> String { wire == .openAI ? wireOpenAI : wireAnthropic }
    func empty(_ model: String) -> String { String(format: emptyFormat, model) }
    func fetched(_ count: Int) -> String { String(format: fetchedFormat, count) }
    func modelCount(_ count: Int) -> String { String(format: modelCountFormat, count) }
    func deleteTitle(_ name: String) -> String { String(format: deleteTitleFormat, name) }

    /// The server's own words follow ours when it gave any.
    func failure(_ failure: NotchChatFailure) -> String {
        switch failure {
        case .missingKey: return failureKey
        case .invalidServer: return failureServerURL
        case .unauthorized: return failureUnauthorized
        case .notFound: return failureNotFound
        case .rateLimited: return failureRate
        case .offline: return failureOffline
        case .badResponse: return failureResponse
        case .server(let status, let message):
            let ours = String(format: failureServerFormat, status)
            return message.map { "\(ours) \($0)" } ?? ours
        }
    }
}

